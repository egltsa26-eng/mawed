def _span(ctx, a, b):
    return f"من {ctx['wday'](a)} {ctx['gtext'](a)} إلى {ctx['wday'](b)} {ctx['gtext'](b)}"


def _has_weekend(a, b):
    d = a
    while d <= b:
        if d.weekday() in (4, 5):
            return True
        d += timedelta(days=1)
    return False


